#What is indentation?
#Indentation refers to the spaces at the beginning of a code line.
#It is used to define a block of code.

#Where indentation is used?
#Indentation is used in loops, conditionals, functions, classes, etc.

#What is the default indentation?
#The default indentation is 4 spaces.

#Where indentation starts?
#Indentation starts immediately after a colon(:).