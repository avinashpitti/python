# Identifiers are the names used to identify a variable, function,
# class, module or other object.

#In short, Anything you name in python is identifier.

#Rules for Identifiers
# 1. Identifiers should start with a letter or an underscore (_).
# 2. Identifiers can only contain letters, digits, and underscores.
# 3. Identifiers are case-sensitive.
# 4. Identifiers should be descriptive and meaningful.
# 5. Identifiers should not be reserved keywords.
# 6. Naming conventions:
    # snake_case for variables and functions
    # PascalCase for classes
    # uppercase for constants


