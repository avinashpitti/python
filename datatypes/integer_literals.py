a=15     #Decimal format-It's default format(Base 10)

#Binary format-It's prefix is 0b(Base 2)
b=0b1111  #Binary Format (Base 2)

#Octal format-It's prefix is 0o(Base 8)
c=0o17   #Octal Format  (Base 8)

#HexaDecimal format-It's prefix is 0x(Base 16)
# Hexa(6)are represented by A-F decimal(10)from 0-9
d=0xf    #HexaDecimal format(Base 16)
print(a)      #15
print(b)
print(c)
print(d)
print("**********Data Types***********")
print(type(a))  #<class,int>
print(type(b))
print(type(c))
print(type(d))